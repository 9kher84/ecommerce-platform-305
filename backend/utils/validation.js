// ملف المرافق لعمليات التحقق من الصحة (Validation)

/**
 * يتحقق مما إذا كان المعرف (ID) هو UUID صالحًا (36 حرفًا) 
 * وهو التنسيق الذي نستخدمه لمعرفات PostgreSQL/UUID.
 * @param {string} id المعرف المراد التحقق منه.
 * @returns {boolean} صحيح إذا كان المعرف صالحًا، خطأ خلاف ذلك.
 */
exports.validateId = (id) => {
    // تعبير نموذجي للتحقق من صحة UUID v4
    // يستخدم لضمان أن المعرفات المرسلة عبر المسارات هي تنسيق UUID صحيح لتجنب أخطاء قاعدة البيانات
    const uuidRegex = /^[0-9a-f]{8}-[0-9a-f]{4}-[4][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
    
    // لتبسيط عملية التحقق، سنتحقق مبدئياً من أنه سلسلة نصية وغير فارغة
    if (typeof id !== 'string' || id.trim() === '') {
        return false;
    }
    
    // بما أننا نستخدم تنسيق UUID في المشروع، يجب أن يطابق التعبير
    return uuidRegex.test(id);
};

